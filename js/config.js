const DATA_PATHS = {

    // --------------------------------------------------------
    // AOIs
    // --------------------------------------------------------

    aois:
        "data/AOIs_Selected_Geojson.geojson",

    // --------------------------------------------------------
    // NDVI
    // --------------------------------------------------------

    ndvi: {},

    // --------------------------------------------------------
    // Mangrove masks
    // --------------------------------------------------------

    masks: {}

};


// ============================================================
// AUTOMATICALLY CREATE AOI/YEAR PATHS
// ============================================================

AOI_NAMES.forEach(function(aoi) {

    DATA_PATHS.ndvi[aoi] = {};
    DATA_PATHS.masks[aoi] = {};

    YEARS.forEach(function(year) {

        DATA_PATHS.ndvi[aoi][year] =
            "data/ndvi_rasters/" +
            aoi +
            "_ndvi_" +
            year +
            ".tif";

        DATA_PATHS.masks[aoi][year] =
            "data/mangrove_masks/" +
            aoi +
            "_mask_" +
            year +
            ".tif";

    });

});


